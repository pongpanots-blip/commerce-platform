/**
 * Minimal Result type for expressing success/failure without throwing.
 * Used where a caller should branch on outcome (e.g. adapter operations).
 */
export type Result<T, E = Error> =
  | { ok: true; value: T }
  | { ok: false; error: E };

export const ok = <T>(value: T): Result<T, never> => ({ ok: true, value });

export const err = <E>(error: E): Result<never, E> => ({ ok: false, error });
